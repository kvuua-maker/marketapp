/** Classifies a raw supplier category + title into a canonical storefront category. */
export function classifyCategory({ categoryRaw = '', title = '', description = '' } = {}) {
  const haystack = `${categoryRaw} ${title} ${description.slice(0, 300)}`.toLowerCase();
  for (const [category, pattern] of RULES) {
    if (pattern.test(haystack)) return category;
  }
  return FALLBACK_CATEGORY;
}

export function isCanonicalCategory(value) {
  return CANONICAL_CATEGORIES.includes(value);
}

/** Normalises whatever the model returned to a guaranteed canonical category. */
export function coerceCategory(value, fallbackText = {}) {
  if (isCanonicalCategory(value)) return value;
  if (typeof value === 'string' && value.trim()) {
    const direct = CANONICAL_CATEGORIES.find(
      (category) => category.toLowerCase() === value.trim().toLowerCase(),
    );
    if (direct) return direct;
  }
  return classifyCategory(fallbackText);
}
