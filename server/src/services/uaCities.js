export function searchCities(query, limit = 20) {
  const needle = String(query ?? '').trim().toLowerCase();
  const list = needle ? UA_CITIES.filter((city) => city.toLowerCase().includes(needle)) : UA_CITIES;
  return list.slice(0, limit);
}
